"""runs_build read from .harness/config.yaml (backlog #8) and
"Can't resolve 'node_modules/...'" as an environment failure (backlog #10)."""
import pytest

from config import harness_runs_build, runs_build_source
from validation import (classify_environment_failure, environment_hint,
                        missing_node_modules_packages)

TAIL = ("Error: Can't resolve 'node_modules/mpa-js/bootstrap/bootstrap.bundle.min.js' in "
        "'/home/runner/work/x/service/mpa-web'\n"
        "Error: Can't resolve 'node_modules/mpa-js/jquery/jquery-2.2.4.min.js' in '/x'\n"
        "Error: Can't resolve 'node_modules/@acme/ui/dist/a.css' in '/x'\n")


# ---------------------------------------------------------------- runs_build
@pytest.mark.parametrize("cfg,env,expected,source", [
    ("runs_build: false\n", "true", False, ".harness/config.yaml"),
    ("runs_build: true\n", "false", True, ".harness/config.yaml"),
    ("runs_build: 'no'\n", "", False, ".harness/config.yaml"),
    ("test_command: x\n", "false", False, "caller workflow (runs_build input)"),
    ("test_command: x\n", "", True, "default"),
])
def test_runs_build_precedence(tmp_path, monkeypatch, cfg, env, expected, source):
    (tmp_path / "config.yaml").write_text(cfg)
    monkeypatch.setenv("HARNESS_RUNS_BUILD", env)
    assert harness_runs_build(tmp_path) is expected
    assert runs_build_source(tmp_path) == source


def test_no_harness_dir_keeps_the_old_behaviour(monkeypatch):
    monkeypatch.setenv("HARNESS_RUNS_BUILD", "false")
    assert harness_runs_build() is False


# ------------------------------------------------------- node_modules missing
def test_node_modules_path_is_an_environment_failure():
    assert classify_environment_failure(1, TAIL) == "node_modules_missing"
    assert "npm install" in environment_hint("node_modules_missing")
    assert missing_node_modules_packages(TAIL) == ["mpa-js", "@acme/ui"]


def test_bare_package_import_stays_a_code_failure():
    out = ("ERROR in ./src/app/x.ts\nModule not found: Error: Can't resolve "
           "'left-pad' in '/x/src/app'\n")
    assert classify_environment_failure(1, out) is None


def test_validation_summary_names_the_packages(tmp_path):
    import validation
    hd = tmp_path / ".harness"
    hd.mkdir()
    (hd / "config.yaml").write_text(
        "test_command: \"printf \\\"Error: Can't resolve 'node_modules/mpa-js/a.js' in '/x'\\\\n\\\"; exit 1\"\n")
    vr = validation.run_validation(tmp_path, hd, log=lambda *a: None)
    assert vr.failure_kind == "environment" and vr.env_reason == "node_modules_missing"
    assert "mpa-js" in vr.summary
